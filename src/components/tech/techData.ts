// Helper: Group tech items by domain
export const getDomainClusters = (): DomainClusterInfo[] => {
  const domainKeys: DomainId[] = [
    "languages",
    "frontend",
    "backend",
    "databases",
    "systems",
    "ai_cloud",
  ];
  return domainKeys.map((key) => {
    const info = VAULT_CONFIG.domains[key];
    const items = TECH_VAULT_ITEMS.filter((item) => item.domain === key);
    return {
      id: key,
      name: info.name,
      hue: info.hue,
      borderRgba: info.borderRgba,
      glowRgba: info.glowRgba,
      bgGradient: info.bgGradient,
      items,
    };
  });
};
